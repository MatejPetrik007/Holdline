// Generates HoldlinePinnedKeys.h/.cpp: the public keys compiled into the firmware.
// SPDX-License-Identifier: GPL-3.0-only
//
//   node gen-pinned-keys.mjs --roots keys/roots.json --out <dir>     real root keys
//   node gen-pinned-keys.mjs --dev --out <dir>                       throwaway root (test vectors)
//
// Pinned are (1) the authority root keys (Ed25519 + ML-DSA-65) that sign key bulletins and
// provisioning bundles, and (2) the publisher keys from site/pubkey.json that sign firmware
// releases. Only PUBLIC keys ever pass through this script.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, '..', '..');
const arg = (n) => { const i = process.argv.indexOf(`--${n}`); return i > -1 ? process.argv[i + 1] : undefined; };
const dev = process.argv.includes('--dev');
const out = arg('out');
if (!out) { console.error('usage: gen-pinned-keys.mjs (--roots <roots.json> | --dev) --out <dir>'); process.exit(2); }

let roots;
if (dev) {
  const v = JSON.parse(readFileSync(join(repo, 'firmware', 'protocol', 'test-vectors', 'vectors.json'), 'utf8'));
  roots = [{ root_id: v.roots.cz.root_id, ed25519: v.roots.cz.ed25519_public, mldsa65: v.roots.cz.mldsa65_public }];
} else {
  const file = arg('roots');
  if (!file || !existsSync(file)) {
    console.error(`No root keys: ${file ?? '(none given)'} does not exist.\n` +
      'A deployable build needs the authority\'s root PUBLIC keys in firmware/household/keys/roots.json\n' +
      '(see firmware/household/keys/README.md). For development use: apply-overlay.sh <dir> --dev-keys');
    process.exit(1);
  }
  roots = JSON.parse(readFileSync(file, 'utf8'));
}
const pub = JSON.parse(readFileSync(join(repo, 'site', 'pubkey.json'), 'utf8'));

const bytes = (hex, len, what) => {
  if (typeof hex !== 'string' || !/^[0-9a-f]*$/i.test(hex) || hex.length !== len * 2) throw new Error(`${what}: expected ${len} bytes of hex`);
  return Buffer.from(hex, 'hex');
};
const cArray = (buf) => { const rows = []; for (let i = 0; i < buf.length; i += 16) rows.push('    ' + [...buf.subarray(i, i + 16)].map((b) => '0x' + b.toString(16).padStart(2, '0')).join(', ')); return rows.join(',\n'); };
const fp = (buf) => createHash('sha256').update(buf).digest('hex');

if (!Array.isArray(roots) || roots.length < 1 || roots.length > 4) throw new Error('1 to 4 root keys expected');
const seen = new Set();
const rootSrc = roots.map((r, i) => {
  if (!Number.isInteger(r.root_id) || r.root_id < 1 || r.root_id > 0xffff || seen.has(r.root_id)) throw new Error(`root ${i}: bad or duplicate root_id`);
  seen.add(r.root_id);
  const ed = bytes(r.ed25519, 32, `root ${r.root_id} ed25519`), pq = bytes(r.mldsa65, 1952, `root ${r.root_id} mldsa65`);
  console.log(`root ${r.root_id}: Ed25519 ${fp(ed)}  ML-DSA-65 ${fp(pq)}`);
  return `    {${r.root_id},\n     {\n${cArray(ed)}},\n     {\n${cArray(pq)}}}`;
});
const pubEd = bytes(pub.Ed25519, 32, 'publisher Ed25519'), pubPq = bytes(pub['ML-DSA-65'], 1952, 'publisher ML-DSA-65');
console.log(`publisher: Ed25519 ${fp(pubEd)}  ML-DSA-65 ${fp(pubPq)}`);
if (dev) console.log('DEVELOPMENT KEYS: the root private key is public (test vectors). Never deploy this build.');

writeFileSync(join(out, 'HoldlinePinnedKeys.h'), `// GENERATED by firmware/household/gen-pinned-keys.mjs. Do not edit.
// SPDX-License-Identifier: GPL-3.0-only
#pragma once
#include "core/hl_trust.h"

namespace holdline_pinned
{
extern const hl::RootKey kRoots[];
extern const size_t kRootCount;
extern const uint8_t kPublisherEd25519[hl::kEdPubLen];
extern const uint8_t kPublisherMldsa65[hl::kMldsaPubLen];
// True when the pinned root is the published throwaway key of the test vectors.
extern const bool kDevKeys;
} // namespace holdline_pinned
`);
writeFileSync(join(out, 'HoldlinePinnedKeys.cpp'), `// GENERATED by firmware/household/gen-pinned-keys.mjs. Do not edit.
// SPDX-License-Identifier: GPL-3.0-only
#include "HoldlinePinnedKeys.h"

namespace holdline_pinned
{
const hl::RootKey kRoots[] = {
${rootSrc.join(',\n')}};
const size_t kRootCount = ${roots.length};
const uint8_t kPublisherEd25519[hl::kEdPubLen] = {
${cArray(pubEd)}};
const uint8_t kPublisherMldsa65[hl::kMldsaPubLen] = {
${cArray(pubPq)}};
const bool kDevKeys = ${dev ? 'true' : 'false'};
} // namespace holdline_pinned
`);
